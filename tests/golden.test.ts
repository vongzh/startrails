import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import { ingest, CLIENT_TARGETS } from '../src/core/index.ts';
import { buildAll, outputFilename } from '../src/pipeline.ts';

const fixture = readFileSync(new URL('../testdata/fixtures/minimal.json', import.meta.url), 'utf8');
const { profile } = ingest(fixture);
const outputs = buildAll(profile);

test('IR × Target 输出被 golden file 逐字锁死', () => {
  assert.equal(outputs.length, CLIENT_TARGETS.length);
  for (const output of outputs) {
    const expected = readFileSync(
      new URL(`../testdata/golden/${outputFilename(output.target)}`, import.meta.url),
      'utf8',
    );
    assert.equal(output.content, expected, `${output.target} 输出与 golden 不一致`);
  }
});

test('Surge 输出为 INI，且只含已核实可表达的协议', () => {
  const surge = outputs.find((output) => output.target === 'surge');
  assert.ok(surge);
  assert.match(surge.content, /^# Generated by Startrails/m);
  assert.match(surge.content, /\[Proxy\]/);
  assert.match(surge.content, /= ss, ss\.example\.invalid, 8388, encrypt-method=aes-128-gcm/);
  assert.match(surge.content, /= vmess, vmess\.example\.invalid, 443, username=/);
  assert.doesNotMatch(surge.content, /= (vless|trojan),/);
});

test('mihomo 输出为 YAML，sing-box 输出为 JSON', () => {
  const mihomo = outputs.find((output) => output.target === 'mihomo');
  const singBox = outputs.find((output) => output.target === 'sing-box');
  assert.ok(mihomo && singBox);
  assert.match(mihomo.content, /type: vless/);
  assert.match(mihomo.content, /type: trojan/);
  assert.match(singBox.content, /"type": "selector"/);
  // shared/tls 结构已核实：带 tls 的节点应写出 tls 对象，而不是被整段丢弃。
  assert.match(singBox.content, /"tls": \{/);
  assert.match(singBox.content, /"server_name":/);
});

test('每个 Target 的构建报告都带跳过计数与可解释诊断', () => {
  for (const output of outputs) {
    assert.ok(output.report.diagnostics.length > 0, output.target);
    assert.equal(output.report.buildId, null);
    assert.equal(output.report.passed + output.report.skipped, profile.nodes.length);
  }
});
